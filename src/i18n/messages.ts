const catalogs: Record<Locale, Catalog> = { en, ar }

export type Vars = Record<string, string | number>

export function translate(locale: Locale, key: string, vars?: Vars): string {
  const template = catalogs[locale][key] ?? catalogs.en[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] != null ? String(vars[name]) : `{${name}}`,
  )
}

export function formatStatusLabel(locale: Locale, status: string): string {
  const key = `status.${status}`
  if (catalogs[locale][key] || catalogs.en[key]) return translate(locale, key)
  return status.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase())
}

export function disputeReasonKey(code: string): string {
  return `disputes.reason.${code}`
}
